-- 1. LEADS TABLE (Contact & Intake Wizard submissions)
CREATE TABLE IF NOT EXISTS public.leads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL,
    phone TEXT,
    company TEXT,
    services TEXT,
    budget TEXT,
    timeline TEXT,
    details TEXT,
    status TEXT DEFAULT 'new',
    ip_address TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. APPOINTMENTS TABLE (Think Bot AI bookings)
CREATE TABLE IF NOT EXISTS public.appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_name TEXT NOT NULL,
    client_email TEXT NOT NULL,
    client_phone TEXT,
    meeting_date TEXT NOT NULL,
    meeting_time TEXT NOT NULL,
    topic TEXT,
    status TEXT DEFAULT 'confirmed',
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. ROI ASSESSMENTS TABLE (Calculadora ROI)
CREATE TABLE IF NOT EXISTS public.roi_assessments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    traffic BIGINT NOT NULL,
    ticket_gs BIGINT NOT NULL,
    conversion_rate NUMERIC NOT NULL,
    projected_conversion_rate NUMERIC NOT NULL,
    current_monthly_revenue_gs BIGINT NOT NULL,
    projected_monthly_revenue_gs BIGINT NOT NULL,
    extra_annual_revenue_gs BIGINT NOT NULL,
    multiplier NUMERIC NOT NULL,
    contact_email TEXT,
    ip_address TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. SITE VISITS TABLE (Landing page traffic analytics)
CREATE TABLE IF NOT EXISTS public.site_visits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ip_address TEXT,
    user_agent TEXT,
    referrer TEXT,
    path TEXT DEFAULT '/',
    device_type TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. CHAT LOGS TABLE (Think Bot AI conversations)
CREATE TABLE IF NOT EXISTS public.chat_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id TEXT,
    user_message TEXT,
    bot_response TEXT,
    intent TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- =========================================================================
-- ROW LEVEL SECURITY (RLS) POLICIES
-- Allows website visitors to submit records and read/update operations
-- =========================================================================

-- Leads Security
ALTER TABLE public.leads ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Allow public insert to leads" ON public.leads;
DROP POLICY IF EXISTS "Allow public read to leads" ON public.leads;
DROP POLICY IF EXISTS "Allow public update to leads" ON public.leads;
DROP POLICY IF EXISTS "Allow public delete to leads" ON public.leads;
CREATE POLICY "Allow public insert to leads" ON public.leads FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public read to leads" ON public.leads FOR SELECT USING (true);
CREATE POLICY "Allow public update to leads" ON public.leads FOR UPDATE USING (true);
CREATE POLICY "Allow public delete to leads" ON public.leads FOR DELETE USING (true);

